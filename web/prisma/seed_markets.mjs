async function main() {
  console.log("Seeding initial markets...");
  for (const m of DEFAULT_MARKETS) {
    await prisma.market.upsert({
      where: { symbol: m.symbol },
      update: m,
      create: m,
    });
  }
  const count = await prisma.market.count();
  console.log(`Success! Total markets in DB: ${count}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
